-- V7: relatos do cidadão (#15).
--
-- O cidadão manda tipo, descrição, posição e (opcional) foto. Nasce PENDENTE; só o que o admin
-- aprova aparece no mapa, por um tempo (ocorrencia.validade). Se a conta do autor ou de quem
-- analisou for excluída (#19), o relato fica, sem dono (ON DELETE SET NULL).

CREATE TABLE TBL_OCORRENCIA (
    ID_OCORRENCIA       BIGINT          NOT NULL    PRIMARY KEY AUTO_INCREMENT,
    TX_TIPO             VARCHAR(30)     NOT NULL,
    TX_DESCRICAO        VARCHAR(500)    NOT NULL,
    TX_FOTO             VARCHAR(60)     NULL,
    NR_LATITUDE         DECIMAL(9, 6)   NOT NULL,
    NR_LONGITUDE        DECIMAL(9, 6)   NOT NULL,
    ID_USUARIO          BIGINT          NULL,
    TX_SITUACAO         VARCHAR(10)     NOT NULL,
    ID_ANALISTA         BIGINT          NULL,
    DT_DATA_ANALISE     DATETIME(2)     NULL,
    TX_MOTIVO_RECUSA    VARCHAR(300)    NULL,
    DT_DATA_CRIACAO     DATETIME(2)     NOT NULL,

    CONSTRAINT FK_OCO_USUARIO  FOREIGN KEY (ID_USUARIO)  REFERENCES TBL_USUARIO (ID_USUARIO) ON DELETE SET NULL,
    CONSTRAINT FK_OCO_ANALISTA FOREIGN KEY (ID_ANALISTA) REFERENCES TBL_USUARIO (ID_USUARIO) ON DELETE SET NULL,
    CONSTRAINT CHK_OCO_TIPO     CHECK (TX_TIPO IN ('BUEIRO_ENTUPIDO', 'ALAGAMENTO', 'LIXO_NA_VIA', 'OUTRO')),
    CONSTRAINT CHK_OCO_SITUACAO CHECK (TX_SITUACAO IN ('PENDENTE', 'APROVADA', 'RECUSADA')),
    CONSTRAINT CHK_OCO_LATITUDE  CHECK (NR_LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CHK_OCO_LONGITUDE CHECK (NR_LONGITUDE BETWEEN -180 AND 180)
);

CREATE INDEX IDX_OCO_SITUACAO_ANALISE ON TBL_OCORRENCIA (TX_SITUACAO, DT_DATA_ANALISE);
CREATE INDEX IDX_OCO_USUARIO_CRIACAO  ON TBL_OCORRENCIA (ID_USUARIO, DT_DATA_CRIACAO);
